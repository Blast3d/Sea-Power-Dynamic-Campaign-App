export interface MissionUnitSpec {
  sectionName: string; // e.g. Taskforce1Vessel1
  unitType: string;
  variantReference?: string;
  relativePositionNM: [number, number, number];
  heading: number;
  telegraph: number;
  isAnchor: boolean;
}

export interface MissionSpec {
  missionDisplayName: string;
  briefing: string;
  objectiveText: string;
  playerUnits: MissionUnitSpec[]; // [0] must be the anchor
  enemyUnits: MissionUnitSpec[];
  /** Patrol duration in seconds for the guaranteed completion path. */
  patrolSeconds: number;
  /** Seconds after completion before the mission exits. */
  exitDelaySeconds: number;
  introDelaySeconds: number;
}

function unitSection(taskforce: string, u: MissionUnitSpec, isPlayer: boolean): string {
  const lines = [
    `[${u.sectionName}]`,
    `Type=${u.unitType}`,
  ];
  if (u.variantReference) lines.push(`VariantReference=${u.variantReference}`);
  lines.push(
    `MissionType=NoMission`,
    // Conservative player defaults per mission-generation reference:
    // radars off, stores full, no damage. Enemy keeps radars on so it can
    // fight, weapons free.
    `WeaponStatus=Free`,
    `RadarsActive=${isPlayer ? "False" : "True"}`,
    `CrewSkill=Trained`,
    `Stores=Full`,
    `Damage=None`,
    `RelativePositionInNM=${u.relativePositionNM.join(",")}`,
    `Heading=${u.heading}`,
    `Telegraph=${u.telegraph}`,
  );
  if (u.isAnchor) lines.push(`TaskForceModeAnchor=True`);
  void taskforce;
  lines.push(``);
  return lines.join("\n");
}

/**
 * Generate a Task Force Mode `Generated` mission.
 *
 * Structure (all syntax verified against community guides):
 * - Trigger1: timed intro message.
 * - Trigger2: completion = patrol timer OR all enemy vessels destroyed —
 *   the mission stays completable even if enemies never engage. Completion
 *   fires the completion message, objective complete, victory, and enables +
 *   reactivates the delayed-exit trigger.
 * - Trigger3 (Disabled=True): delayed exit after `exitDelaySeconds`.
 */
export function generateMissionIni(spec: MissionSpec): string {
  const enemySections = spec.enemyUnits.map((u) => u.sectionName);
  const hasEnemies = enemySections.length > 0;

  const missionLines = [
    `; Generated Task Force Mode mission (playtest export).`,
    ``,
    `[Mission]`,
    `PlayerTaskforce=Taskforce1`,
    `NumberOfTaskforce1Vessels=${spec.playerUnits.length}`,
  ];
  if (hasEnemies) {
    missionLines.push(`NumberOfTaskforce2Vessels=${spec.enemyUnits.length}`);
  }
  missionLines.push(`NumberOfTriggers=3`, ``);

  const unitSections = [
    ...spec.playerUnits.map((u) => unitSection("Taskforce1", u, true)),
    ...spec.enemyUnits.map((u) => unitSection("Taskforce2", u, false)),
  ];

  const completionConditions = hasEnemies
    ? `<PatrolComplete> OR <EnemyDestroyed>`
    : `<PatrolComplete>`;

  const triggerSections = [
    [
      `[Trigger1]`,
      `Name=Intro briefing`,
      `Condition_Intro_Type=Time`,
      `Condition_Intro_Time=${spec.introDelaySeconds}`,
      `ConditionsCompleted=<Intro>`,
      `Action_Taskforce1_Message=IntroMessage`,
      ``,
    ].join("\n"),
    [
      `[Trigger2]`,
      `Name=Primary objective complete`,
      `Condition_PatrolComplete_Type=Time`,
      `Condition_PatrolComplete_Time=${spec.patrolSeconds}`,
      ...(hasEnemies
        ? [
            `Condition_EnemyDestroyed_Type=UnitDestroyed`,
            `Condition_EnemyDestroyed_Units=${enemySections.join(",")}`,
          ]
        : []),
      `ConditionsCompleted=${completionConditions}`,
      `Action_Taskforce1_Message=CompletionMessage`,
      `Action_ObjectivesCompleted=Objective_Primary`,
      `Action_Victory=Taskforce1`,
      `Action_EnableTriggers=Trigger3`,
      `Action_ReactivateTriggers=Trigger3`,
      ``,
    ].join("\n"),
    [
      `[Trigger3]`,
      `Name=Delayed mission exit`,
      `Disabled=True`,
      `Condition_ExitTimer_Type=Time`,
      `Condition_ExitTimer_Time=${spec.exitDelaySeconds}`,
      `ConditionsCompleted=<ExitTimer>`,
      `Action_EndMission=True`,
      ``,
    ].join("\n"),
  ];

  const language = [
    `[Language_en]`,
    `StartIntel=${spec.objectiveText}`,
    `Objective_Primary=${spec.objectiveText}`,
    `IntroMessage=Mission Briefing|${spec.briefing}|Acknowledged`,
    `CompletionMessage=<size=40><color=Lime>MISSION COMPLETE</color></size>|${spec.missionDisplayName}: primary objective achieved. Prepare to return to station.|Continue`,
    ``,
  ].join("\n");

  return [missionLines.join("\n"), ...unitSections, ...triggerSections, language].join("\n");
}

// ---------------------------------------------------------------------------
// Reference-mission merge for unverified [Mission] keys
// ---------------------------------------------------------------------------

/** Keys the generator owns; reference values for these are never copied. */
const OWNED_MISSION_KEY_PATTERNS = [
  /^PlayerTaskforce$/i,
  /^NumberOfTaskforce\d+/i,
  /^NumberOfTriggers$/i,
  /^NumberOfCivilianRoutes$/i,
  /^Taskforce\d+_Formation/i,
];

/**
 * Copy unknown `[Mission]`-section keys (world location, date, environment,
 * etc.) from a read-only base-game reference mission into a generated
 * mission. Only the [Mission] section is merged; no other reference content
 * (units, triggers, language) is copied.
 */
export function mergeReferenceMissionKeys(
  generatedMission: string,
  referenceMissionText: string,
): string {
  // Extract reference [Mission] section key lines.
  const refKeys: string[] = [];
  let inMission = false;
  for (const raw of referenceMissionText.split(/\r?\n/)) {
    const line = raw.replace(/^﻿/, "").trim();
    if (line.startsWith("[")) {
      inMission = /^\[Mission\]/i.test(line);
      continue;
    }
    if (!inMission || line === "" || line.startsWith(";") || line.startsWith("//")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    if (OWNED_MISSION_KEY_PATTERNS.some((p) => p.test(key))) continue;
    refKeys.push(line);
  }
  if (refKeys.length === 0) return generatedMission;

  // Insert after our [Mission] section's own keys (before first blank line
  // following the section header).
  const lines = generatedMission.split("\n");
  const missionIdx = lines.findIndex((l) => l.trim() === "[Mission]");
  if (missionIdx < 0) return generatedMission;
  let insertAt = missionIdx + 1;
  while (insertAt < lines.length && lines[insertAt].trim() !== "" && !lines[insertAt].startsWith("[")) {
    insertAt += 1;
  }
  const annotated = [
    `; --- Keys below copied from read-only reference mission (location/date/environment) ---`,
    ...refKeys,
  ];
  return [...lines.slice(0, insertAt), ...annotated, ...lines.slice(insertAt)].join("\n");
}
