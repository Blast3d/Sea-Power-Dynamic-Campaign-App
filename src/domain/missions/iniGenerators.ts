/**
 * Sea Power .ini file generators for Task Force Mode campaigns.
 *
 * Syntax sources (see docs/REFERENCE_INDEX.md):
 * - Task Force Mode campaign/roster structure: skill reference
 *   `skills/sea-power-campaign-planning/references/task-force-mode.md`.
 * - Mission trigger syntax (`Condition_<Name>_Type`, `ConditionsCompleted`,
 *   `Action_*`, delayed-exit pattern), `[Language_en]` `Title|Body|Button`
 *   message format, and vessel keys: Steam community mission guides
 *   (Mission Creation Community Guide; Triggers and Conditions Guide).
 * - Player start defaults (radars off, stores full, damage none):
 *   `references/mission-generation.md`.
 *
 * Unknown [Mission]-level keys (world location, date, environment) are NOT
 * invented: they are copied from a read-only base-game reference mission
 * when one is provided (`mergeReferenceMissionKeys`).
 */

import type { UnitCatalogEntry } from "../catalog/unitCatalog";

// ---------------------------------------------------------------------------
// Campaign-level inputs
// ---------------------------------------------------------------------------

export interface CampaignFileSpec {
  campaignFolder: string;
  displayName: string;
  defaultTaskForceName: string;
  difficultyPresets: string[]; // e.g. ["Easy", "Moderate", "Difficult"]
  defaultPreset: string;
  startingPoints: number;
  pointCap: number;
  missionFileName: string; // file name inside missions/
  missionDisplayName: string;
  threat: { ship: boolean; air: boolean; sub: boolean; land: boolean };
  completionPoints: number;
}

/** Difficulty presets follow the documented section layout. */
function difficultySection(id: string, startingPoints: number, pointCap: number): string {
  const modifiers: Record<string, { repair: number; points: number }> = {
    Easy: { repair: 0.5, points: Math.round(startingPoints * 1.25) },
    Moderate: { repair: 1, points: startingPoints },
    Difficult: { repair: 1.5, points: Math.round(startingPoints * 0.8) },
  };
  const m = modifiers[id] ?? { repair: 1, points: startingPoints };
  return [
    `[TaskForceModeDifficulty_${id}]`,
    `Name=${id}`,
    `StartingPoints=${m.points}`,
    `PointCap=${Math.max(pointCap, m.points)}`,
    `ShipIncludesAirwing=True`,
    `PurchaseLoadouts=True`,
    `InitialUnlockedLoadouts=Default|Early`,
    `RepairCostModifier=${m.repair}`,
    `UnitDecommissionPointReturnModifier=0.25`,
    `UnitDismissPointReturnModifier=0.5`,
    `CrewSkillInitial=Trained`,
    ``,
  ].join("\n");
}

export function generateCampaignIni(spec: CampaignFileSpec): string {
  const threatLine = (label: string, on: boolean, weight: number) =>
    `TaskForceModeThreatProfile${label}=${on ? `True,${weight}` : "False"}`;
  const lines = [
    `; Generated by Sea Power Dynamic Campaign (playtest export).`,
    `; Campaign: ${spec.displayName}`,
    ``,
    `[Campaign]`,
    `Type=Linear`,
    `Length=1`,
    ``,
    `[TaskForceMode]`,
    `Enabled=True`,
    `DefaultTaskForceName=${spec.defaultTaskForceName}`,
    `CommanderSettingsFile=commander_settings.ini`,
    `RosterFile=player_task_force_roster.ini`,
    `TaskForceDifficultyPresets=${spec.difficultyPresets.join("|")}`,
    `DefaultTaskForceDifficultyPreset=${spec.defaultPreset}`,
    `StartingPoints=${spec.startingPoints}`,
    `PointCap=${spec.pointCap}`,
    `ShipIncludesAirwing=True`,
    `PurchaseLoadouts=True`,
    ``,
  ];
  for (const preset of spec.difficultyPresets) {
    lines.push(difficultySection(preset, spec.startingPoints, spec.pointCap));
  }
  lines.push(
    `[Mission1]`,
    `MissionFile=campaigns/${spec.campaignFolder}/missions/${spec.missionFileName}`,
    `TaskForceModeMissionGenerationType=Generated`,
    `IsUnlocked=True`,
    `TaskForceModeIncludesTaskForce=True`,
    `TaskForceModeIncludesAirwing=False`,
    `TaskForceModeIncludesSubmarine=False`,
    threatLine("Ship", spec.threat.ship, 3),
    threatLine("Air", spec.threat.air, 2),
    threatLine("Sub", spec.threat.sub, 3),
    threatLine("Land", spec.threat.land, 1),
    `TaskForceModeRearm=True`,
    `TaskForceModeRepair=True`,
    `TaskForceModeEnableTaskForceBuilder=True`,
    `TaskForceModeCompletionPoints=${spec.completionPoints}`,
    `TaskForceModeCompletionCapPoints=${spec.completionPoints}`,
    ``,
  );
  return lines.join("\n");
}

