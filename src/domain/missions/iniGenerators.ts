export interface RosterSpec {
  /** Discovered, export-eligible units only — validated upstream. */
  vessels: UnitCatalogEntry[];
  submarines: UnitCatalogEntry[];
  aircraft: UnitCatalogEntry[];
  helicopters: UnitCatalogEntry[];
  /** Fallback cost when a discovered unit has no parsed TaskForceCost. */
  fallbackCost: number;
}

function rosterLine(u: UnitCatalogEntry, refs: string[], fallbackCost: number): string {
  const cost = u.taskForceCost ?? fallbackCost;
  const refPart = refs.length > 0 ? refs.join(",") : "";
  return `${u.unitType}=${refPart}|${cost}`;
}

export function generateRosterIni(spec: RosterSpec): string {
  const section = (
    name: string,
    units: UnitCatalogEntry[],
    refsOf: (u: UnitCatalogEntry) => string[],
  ): string[] =>
    units.length === 0
      ? []
      : [`[${name}]`, ...units.map((u) => rosterLine(u, refsOf(u), spec.fallbackCost)), ``];

  return [
    `; Generated player Task Force Builder roster.`,
    `; Ships/submarines list VariantReference names; aircraft/helicopters list SquadronReference names.`,
    ``,
    ...section("AllowedVessels", spec.vessels, (u) => u.variants),
    ...section("AllowedSubmarines", spec.submarines, (u) => u.variants),
    ...section("AllowedAircraft", spec.aircraft, (u) => u.squadrons),
    ...section("AllowedHelicopters", spec.helicopters, (u) => u.squadrons),
  ].join("\n");
}

